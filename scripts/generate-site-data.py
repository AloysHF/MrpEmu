#!/usr/bin/env python3
"""Generate site/js/compat-data.js from docs/Game-Compatibility.md.

The website ships a small JavaScript manifest instead of parsing Markdown in
the browser, so the gallery works on GitHub Pages and from a local checkout.
Run this after editing the compatibility table.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "Game-Compatibility.md"
OUT = ROOT / "site" / "js" / "compat-data.js"

ROW = re.compile(
    r"^\|\s*(\d+)\s*\|\s*`([^`]+\.mrp)`\s*\|\s*([^|]+?)\s*"
    r"\|\s*<img src=\"([^\"]+)\"[^>]*>\s*\|\s*([^|]+?)\s*"
    r"\|\s*([^|]+?)\s*\|\s*(.+?)\s*\|$"
)

def main() -> int:
    text = DOC.read_text(encoding="utf-8")
    entries = []
    for line in text.splitlines():
        match = ROW.match(line.strip())
        if not match:
            continue
        number, package, screen, image, status, capture, note = match.groups()
        entries.append(
            {
                "n": int(number),
                "package": package,
                "title": package[:-4],
                "screen": screen.strip(),
                "image": image.strip(),
                "status": status.strip(),
                "capture": capture.strip(),
                "note": note.strip(),
            }
        )

    if not entries:
        print(f"No compatibility rows found in {DOC}", file=sys.stderr)
        return 1

    payload = json.dumps(entries, ensure_ascii=False, indent=2)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/generate-site-data.py from docs/Game-Compatibility.md.\n"
        "// Do not edit by hand; rerun the generator after changing the table.\n"
        f"window.MRP_COMPAT = {payload};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(entries)} entries to {OUT.relative_to(ROOT)}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
